"""
Injects the generated silhouette into the View 1 component.

It replaces the whole <g id="bodyAnatomyGroup"> block and recomputes the leader
lines so their anchors match the new anatomical references.
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from generate_silhouette import (  # noqa: E402
    AXIS_X,
    KNEE_OFFSET,
    ORGANS,
    build_anatomical_group,
    build_organs,
)

PATH = Path(__file__).resolve().parent / "components" / "view_biomedical.html"
OFFSET = (180, 10)  # transform of the anatomical group

# Frame grid (680x500 canvas). The canonical figure occupies x 277..403, narrower
# than the previous one, so the cards widen and move closer to avoid dead gaps:
# left channel x 10..242, right channel x 438..670.
LEFT_TERMINAL, RIGHT_TERMINAL = 248, 432
LEFT_BUS = 262


def g(x: float, y: float) -> tuple[float, float]:
    """Converts local body coordinates into canvas coordinates."""
    return x + OFFSET[0], y + OFFSET[1]


def build_guide_lines() -> tuple[str, dict[str, float]]:
    """Generates the five leader lines anchored to the organs and their card heights."""
    _, y_brain = g(0, ORGANS["brain"]["cy"])
    _, y_heart = g(0, ORGANS["heart"]["cy"])
    _, y_hydration = g(0, ORGANS["hydration"]["cy"])
    _, y_lungs = g(0, ORGANS["lungs"]["cy"] - 16)
    _, y_bones = g(0, ORGANS["knee_y"]["cy"])

    x_brain, _ = g(AXIS_X - 20, 0)      # left lobe of the brain
    x_heart, _ = g(150, 0)              # left edge of the myocardium
    x_hydration, _ = g(140, 0)          # left kidney
    x_lungs, _ = g(192, 0)              # right lung lobe
    x_bones, _ = g(AXIS_X + KNEE_OFFSET, 0)  # right knee

    # The hydration card moves down so it does not collide with the heart one.
    y_hydration_card = y_hydration + 40

    blocks = [
        ("brain", "var(--c-cyan)", f"{x_brain:.0f},{y_brain:.0f} {LEFT_TERMINAL},{y_brain:.0f}",
         (LEFT_TERMINAL, y_brain), (x_brain, y_brain)),
        ("heart", "var(--c-red)", f"{x_heart:.0f},{y_heart:.0f} {LEFT_TERMINAL},{y_heart:.0f}",
         (LEFT_TERMINAL, y_heart), (x_heart, y_heart)),
        ("hydration", "var(--c-blue)",
         f"{x_hydration:.0f},{y_hydration:.0f} {LEFT_BUS},{y_hydration:.0f} {LEFT_BUS},{y_hydration_card:.0f} {LEFT_TERMINAL},{y_hydration_card:.0f}",
         (LEFT_TERMINAL, y_hydration_card), (x_hydration, y_hydration)),
        ("lungs", "var(--c-green)", f"{x_lungs:.0f},{y_lungs:.0f} {RIGHT_TERMINAL},{y_lungs:.0f}",
         (RIGHT_TERMINAL, y_lungs), (x_lungs, y_lungs)),
        ("bones", "var(--c-amber)", f"{x_bones:.0f},{y_bones:.0f} {RIGHT_TERMINAL},{y_bones:.0f}",
         (RIGHT_TERMINAL, y_bones), (x_bones, y_bones)),
    ]

    parts = ["""        <!-- LEADER LINES — generated by frontend/apply_silhouette.py
             Left channel x 10..242 (terminal 248) · body x 277..403 · right channel x 438..670 (terminal 432).
             The ordinate of each terminal is the exact center of its card. -->"""]
    for organ, color, points, (tx, ty), (ax, ay) in blocks:
        parts.append(
            f'        <g class="organ-connector-line" data-organ-line="{organ}" pointer-events="none">\n'
            f'          <polyline points="{points}" fill="none" stroke="{color}" stroke-width="2"\n'
            f'                    stroke-linejoin="round" filter="drop-shadow(0 0 5px {color})"></polyline>\n'
            f'          <circle cx="{ax:.0f}" cy="{ay:.0f}" r="4.5" fill="{color}" stroke="#eaf2f8" stroke-width="1.5"></circle>\n'
            f'          <circle cx="{tx:.0f}" cy="{ty:.0f}" r="3" fill="{color}"></circle>\n'
            f'        </g>'
        )

    heights = {
        "brain": y_brain, "heart": y_heart, "hydration": y_hydration_card,
        "lungs": y_lungs, "bones": y_bones,
    }
    return "\n".join(parts), heights


def main() -> None:
    text = PATH.read_text(encoding="utf-8")

    # The generated block is delimited by its own markers so the script is
    # idempotent: a second run replaces its own output.
    OPEN = "<!-- ===== START OF GENERATED BLOCK: SILHOUETTE AND LEADER LINES ===== -->"
    CLOSE = "<!-- ===== END OF GENERATED BLOCK ===== -->"

    lines, heights = build_guide_lines()
    block = (
        f"        {OPEN}\n"
        + build_anatomical_group()
        + build_organs()
        + "\n"
        + lines.lstrip("\n")
        + f"\n        {CLOSE}\n      "
    )

    if OPEN in text:
        start = text.index(OPEN) - 8
        end = text.index(CLOSE) + len(CLOSE) + len("\n      ")
        text = text[:start] + block + text[end:]
    else:
        # First pass: delimit from the comment preceding the anatomical group to
        # the closing of the SVG.
        start = text.rindex("<!--", 0, text.index('<g id="bodyAnatomyGroup"'))
        end = text.index("</svg>", start)
        text = text[:start] + block + text[end:]

    # --- 3. Realign the height of each card to the center of its leader line ---
    for organ, y in heights.items():
        pct = y / 500.0 * 100.0
        text = re.sub(
            rf'(data-organ-card="{organ}"[^>]*?style="top:)[\d.]+%',
            rf'\g<1>{pct:.2f}%',
            text,
            flags=re.S,
        )

    PATH.write_text(text, encoding="utf-8")

    print("Silhouette injected into view_biomedical.html")
    print("\nCard heights realigned:")
    for organ, y in heights.items():
        print(f"  {organ:<14} y={y:6.1f} u  ->  top {y / 500 * 100:.2f}%")


if __name__ == "__main__":
    main()
